"""Run in Blender's Text Editor, with all rocket mesh parts selected.

Output matches earth.h: x, y, z, r, g, b, nx, ny, nz per vertex.
Exports the evaluated meshes (including modifiers) at the current frame.
Vertex colors take priority over the material's constant Base Color.
Image textures and procedural node materials are not baked.
The original Blender objects are not modified. Requires Blender 4.1+.
"""

import math
from pathlib import Path


OUTPUT = Path(r"C:\Users\Alkys\Documents\ZPG\RN Implementace\ZPG\Models\rocket.h")
CENTER_AND_NORMALIZE = True  # Center bounding box; longest dimension becomes 2.
Y_UP = True  # Blender (x, y, z) -> OpenGL (x, z, -y).


def material_color(mesh, index, warnings):
    if index >= len(mesh.materials) or mesh.materials[index] is None:
        return (0.8, 0.8, 0.8)
    material = mesh.materials[index]
    if material.use_nodes and material.node_tree:
        principled = next(
            (node for node in material.node_tree.nodes
             if node.type == "BSDF_PRINCIPLED"), None
        )
        if principled:
            base = principled.inputs.get("Base Color")
            if base is not None:
                if base.is_linked:
                    warnings.add(material.name)
                return tuple(base.default_value[:3])
        warnings.add(material.name)
    return tuple(material.diffuse_color[:3])


def center_and_normalize(rows):
    """Keep all mesh parts together, using one shared bounding box."""
    low = [min(row[axis] for row in rows) for axis in range(3)]
    high = [max(row[axis] for row in rows) for axis in range(3)]
    size = max(high[axis] - low[axis] for axis in range(3))
    if size <= 0:
        raise ValueError("Selected geometry has zero size.")
    center = [(low[axis] + high[axis]) / 2 for axis in range(3)]
    return [tuple((row[axis] - center[axis]) * 2 / size for axis in range(3))
            + row[3:] for row in rows]


def write_header(rows, output):
    if not rows or len(rows) % 3:
        raise ValueError("Expected a nonempty list of triangle vertices.")
    if any(len(row) != 9 or not all(math.isfinite(v) for v in row) for row in rows):
        raise ValueError("Every vertex must contain nine finite values.")
    lines = [
        "#pragma once",
        "// Generated by Blender: position XYZ, color RGB, normal XYZ.",
        f"// vertexCount = {len(rows)}; triangleCount = {len(rows) // 3};",
        "// Use Model::create(rocket, sizeof(rocket), 9).",
        "const float rocket[] = {",
    ]
    lines.extend("    " + ", ".join(f"{value:.8f}f" for value in row) + ","
                 for row in rows)
    lines.append("};\n")
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(".h.tmp")
    temporary.write_text("\n".join(lines), encoding="utf-8")
    temporary.replace(output)


def export_selected():
    import bpy
    from mathutils import Matrix

    if bpy.app.version < (4, 1, 0):
        raise RuntimeError("This script requires Blender 4.1 or newer.")
    if bpy.context.mode != "OBJECT":
        raise RuntimeError("Switch to Object Mode before exporting.")
    objects = [obj for obj in bpy.context.selected_objects if obj.type == "MESH"]
    if not objects:
        raise RuntimeError("Select the rocket's mesh objects first.")

    depsgraph = bpy.context.evaluated_depsgraph_get()
    axes = Matrix.Rotation(-math.pi / 2, 4, "X") if Y_UP else Matrix.Identity(4)
    rows = []
    warnings = set()
    for obj in sorted(objects, key=lambda item: item.name):
        evaluated = obj.evaluated_get(depsgraph)
        mesh = evaluated.to_mesh(preserve_all_data_layers=True, depsgraph=depsgraph)
        try:
            mesh.calc_loop_triangles()
            transform = axes @ evaluated.matrix_world
            normal_matrix = transform.to_3x3().inverted().transposed()
            mirrored = transform.to_3x3().determinant() < 0
            colors = mesh.color_attributes.active_color
            if colors and colors.domain not in {"POINT", "CORNER"}:
                colors = None
            normals = mesh.corner_normals
            for triangle in mesh.loop_triangles:
                fallback = material_color(mesh, triangle.material_index, warnings)
                loops = reversed(triangle.loops) if mirrored else triangle.loops
                for loop_index in loops:
                    vertex_index = mesh.loops[loop_index].vertex_index
                    position = transform @ mesh.vertices[vertex_index].co
                    normal = normal_matrix @ normals[loop_index].vector
                    if normal.length_squared == 0:
                        raise ValueError(f"Zero normal in object {obj.name}.")
                    normal.normalize()
                    color = fallback
                    if colors:
                        color_index = loop_index if colors.domain == "CORNER" else vertex_index
                        color = tuple(colors.data[color_index].color[:3])
                    rows.append(tuple(position) + tuple(color) + tuple(normal))
        finally:
            evaluated.to_mesh_clear()

    if not rows:
        raise RuntimeError("Selected objects contain no triangles.")
    if CENTER_AND_NORMALIZE:
        rows = center_and_normalize(rows)
    write_header(rows, OUTPUT)
    print(f"EXPORTED: {OUTPUT}\nVertices: {len(rows)}, triangles: {len(rows) // 3}")
    if warnings:
        print("Linked/procedural material colors were not baked; using constant colors: "
              + ", ".join(sorted(warnings)))


if __name__ == "__main__":
    export_selected()
